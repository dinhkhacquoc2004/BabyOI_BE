WITH optimized_food_image_seed(id, image_url) AS (
    SELECT seed_id, 'https://res.cloudinary.com/dkerzsvan/image/upload/f_jpg,q_auto/food/Food_' || seed_id || '.jpg'
    FROM generate_series(1, 252) AS seed_id
)
UPDATE "food_library" fl
SET "image_url" = s.image_url,
    "updated_at" = now(),
    "updated_by" = 'system'
FROM optimized_food_image_seed s
WHERE s.id = ((fl."id" - 1) % 252) + 1
  AND (
      fl."image_url" IS NULL
      OR BTRIM(fl."image_url") = ''
      OR fl."image_url" LIKE '/Food/%'
      OR fl."image_url" LIKE 'https://images.unsplash.com/%'
      OR fl."image_url" LIKE 'https://res.cloudinary.com/dkerzsvan/image/upload/%/food/Food_%'
  );
